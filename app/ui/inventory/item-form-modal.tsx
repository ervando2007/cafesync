"use client";

import { useMemo, useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { XIcon } from "@/app/ui/pos/icons";
import { CategoryManagerModal } from "@/app/ui/inventory/category-manager-modal";
import { createStockItem, updateStockItem } from "@/app/inventory/actions";
import type { CategoryOption, StockItemRow, UnitOption } from "@/lib/inventory";
import type { AccountOption } from "@/lib/accounting";
import { useI18n } from "@/app/i18n-provider";

export function ItemFormModal({
  mode,
  item,
  units,
  categories,
  expenseAccounts,
  onClose,
}: {
  mode: "create" | "edit";
  item?: StockItemRow;
  units: UnitOption[];
  categories: CategoryOption[];
  expenseAccounts: AccountOption[];
  onClose: () => void;
}) {
  const router = useRouter();
  const { t } = useI18n();
  const [accountId, setAccountId] = useState(item?.accountId ?? 0);
  const [unitId, setUnitId] = useState(item?.unitId ?? units[0]?.id ?? 0);
  const [categoryId, setCategoryId] = useState(item?.categoryId ?? 0);
  const [reorderLevel, setReorderLevel] = useState(item?.reorderLevel ?? 0);
  const [error, setError] = useState<string | null>(null);
  const [showCategoryManager, setShowCategoryManager] = useState(false);
  const [isPending, startTransition] = useTransition();

  const selectableCategories = useMemo(() => {
    const active = categories.filter((c) => c.status === "ACTIVE");
    if (item && !active.some((c) => c.id === item.categoryId)) {
      const current = categories.find((c) => c.id === item.categoryId);
      if (current) return [current, ...active];
    }
    return active;
  }, [categories, item]);

  const effectiveCategoryId = categoryId || selectableCategories[0]?.id || 0;

  function handleSubmit() {
    setError(null);
    const input = { accountId, unitId, categoryId: effectiveCategoryId, reorderLevel };

    startTransition(async () => {
      const result =
        mode === "create"
          ? await createStockItem(input)
          : await updateStockItem({ ...input, id: item!.stockItemId });

      if (!result.ok) {
        setError(result.message ?? t("common.somethingWentWrong"));
        return;
      }
      router.refresh();
      onClose();
    });
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4">
      <div className="w-full max-w-md rounded-2xl bg-white p-6 shadow-xl">
        <div className="flex items-center justify-between">
          <h2 className="text-lg font-semibold text-gray-900">
            {mode === "create" ? t("inventory.addItemTitle") : t("inventory.editItemTitle")}
          </h2>
          <button
            type="button"
            onClick={onClose}
            className="text-gray-400 hover:text-gray-600"
            aria-label={t("common.close")}
          >
            <XIcon className="h-5 w-5" />
          </button>
        </div>

        {error && (
          <div className="mt-4 rounded-xl bg-red-50 px-4 py-3 text-sm font-medium text-red-700">
            {error}
          </div>
        )}

        <div className="mt-4 space-y-4">
          {mode === "edit" && item && (
            <div>
              <label className="text-xs text-gray-500">SKU</label>
              <p className="mt-1 rounded-lg border border-gray-100 bg-gray-50 px-3 py-2.5 text-sm text-gray-500">
                {item.sku}
              </p>
              <p className="mt-1 text-xs text-gray-400">{t("inventory.skuAutoGeneratedHint")}</p>
            </div>
          )}

          <div>
            <label className="text-xs text-gray-500">{t("inventory.itemAccountLabel")}</label>
            <select
              value={accountId}
              onChange={(e) => setAccountId(Number(e.target.value))}
              className="mt-1 w-full rounded-lg border border-gray-200 px-3 py-2.5 text-sm focus:border-amber-500 focus:outline-none"
            >
              <option value={0} disabled>
                {t("inventory.selectExpenseAccount")}
              </option>
              {expenseAccounts.map((a) => (
                <option key={a.id} value={a.id}>
                  {a.code} — {a.name}
                </option>
              ))}
            </select>
          </div>

          <div className="grid grid-cols-2 gap-4">
            <div>
              <div className="flex items-center justify-between">
                <label className="text-xs text-gray-500">{t("inventory.category")}</label>
                <button
                  type="button"
                  onClick={() => setShowCategoryManager(true)}
                  className="text-xs font-medium text-amber-700 hover:text-amber-800"
                >
                  {t("common.manage")}
                </button>
              </div>
              <select
                value={effectiveCategoryId}
                onChange={(e) => setCategoryId(Number(e.target.value))}
                className="mt-1 w-full rounded-lg border border-gray-200 px-3 py-2.5 text-sm focus:border-amber-500 focus:outline-none"
              >
                {selectableCategories.length === 0 && <option value={0}>{t("inventory.noCategories")}</option>}
                {selectableCategories.map((c) => (
                  <option key={c.id} value={c.id}>
                    {c.name}
                  </option>
                ))}
              </select>
            </div>
            <div>
              <label className="text-xs text-gray-500">{t("inventory.unit")}</label>
              <select
                value={unitId}
                onChange={(e) => setUnitId(Number(e.target.value))}
                className="mt-1 w-full rounded-lg border border-gray-200 px-3 py-2.5 text-sm focus:border-amber-500 focus:outline-none"
              >
                {units.map((u) => (
                  <option key={u.id} value={u.id}>
                    {u.name}
                  </option>
                ))}
              </select>
            </div>
          </div>

          <div>
            <label className="text-xs text-gray-500">{t("inventory.reorderLevel")}</label>
            <input
              type="number"
              min={0}
              step="0.01"
              value={reorderLevel}
              onChange={(e) => setReorderLevel(Number(e.target.value))}
              className="mt-1 w-full rounded-lg border border-gray-200 px-3 py-2.5 text-sm focus:border-amber-500 focus:outline-none"
            />
            <p className="mt-1 text-xs text-gray-400">{t("inventory.reorderLevelHint")}</p>
          </div>
        </div>

        <div className="mt-6 flex justify-end gap-3">
          <button
            type="button"
            onClick={onClose}
            className="rounded-xl border border-gray-200 px-4 py-2.5 text-sm font-medium text-gray-600 hover:bg-gray-50"
          >
            {t("common.cancel")}
          </button>
          <button
            type="button"
            onClick={handleSubmit}
            disabled={
              isPending || units.length === 0 || selectableCategories.length === 0 || !accountId
            }
            className="rounded-xl bg-amber-700 px-5 py-2.5 text-sm font-semibold text-white hover:bg-amber-800 disabled:cursor-not-allowed disabled:opacity-50"
          >
            {isPending ? t("common.saving") : t("inventory.saveItem")}
          </button>
        </div>
      </div>

      {showCategoryManager && (
        <CategoryManagerModal
          categories={categories}
          onClose={() => setShowCategoryManager(false)}
        />
      )}
    </div>
  );
}
